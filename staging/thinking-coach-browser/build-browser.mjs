// Deterministic private closure build: retain original Node core/tests unchanged.
// No runtime eval, import maps, Node shims, or caller-object inspection in the browser entrypoint.
import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const read = file => fs.readFileSync(new URL(file, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const hashes = {};
function source(file) {
  const text = read(file); hashes[file] = createHash('sha256').update(text).digest('hex'); return text;
}
function replaceOnce(text, from, to) {
  assert.equal(text.split(from).length - 1, 1, 'Build transform must match one exact site');
  return text.replace(from, to);
}
let identity = source('../thinking-coach-core/identity.mjs').replace(/^import .*\n/gm, '').replaceAll('export ', '');
identity = replaceOnce(identity, "requireCondition(!types.isProxy(value), 'PROXY_NOT_ALLOWED');",
  '// Private parsed JSON / engine data only. This is NOT browser Proxy detection.');
identity = replaceOnce(identity, "createHash('sha256').update(stable(value)).digest('hex')", 'sha256Text(stable(value))');
let rules = source('../thinking-coach-core/rules.mjs').replace(/^import .*identity\.mjs';\n/gm, '').replaceAll('export ', '');
let core = source('../thinking-coach-core/core.mjs').replace(/^import .*\n/gm, '')
  .replace(/^export \{ EVIDENCE_KIND \} from .*\n/gm, '').replaceAll('export ', '');
const hash = source('./sha256.mjs').replaceAll('export ', ''), protocol = source('./protocol.template.mjs');
const body = [hash, identity, rules, core, protocol].join('\n');
assert(!body.includes('node:')); assert(!body.includes('types.isProxy'));
const output = '// GENERATED by build-browser.mjs; do not edit. Private data functions are not exported.\n'
  + '// Input SHA-256 (LF-normalized build text, not a production content manifest): '+JSON.stringify(hashes)+'\n'+body;
const target = new URL('./browser-coach.mjs', import.meta.url);
if (process.argv.includes('--check')) assert.equal(read('./browser-coach.mjs'), output, 'Browser build drift');
else fs.writeFileSync(target, output);
console.log(JSON.stringify({ status:'PASS', mode:process.argv.includes('--check')?'check':'build', inputs:hashes }));
